"""Full-game tracer e2e (plan 02-03 Task 3, Gate 1).

The real competition binary plays a scripted full game: journal → MoveLog
projection → game-<id>.log rendered → lint_log in-process, exit 0 with
`OK fullgame`. Asserts the plan's acceptance criteria on the log rows:
all eleven §3.1 keys, src=opp zeros + measured wall, src=search depth>0,
wall_ms ≥ engine_ms everywhere, lint zero failures.

The committed golden fixture (console/tests/fixtures/golden-game.log) is
generated by this test's real-engine run shape and re-linted every run.
"""

import pathlib
import subprocess
import sys
import tempfile
import unittest

REPO = pathlib.Path(__file__).parent.resolve().parent.parent
sys.path.insert(0, str(REPO / "vendor"))
sys.path.insert(0, str(REPO / "console" / "src"))

from console.log.lint import lint_log  # noqa: E402

# Row-level assertions (§3.1 keys, §4 fills) reuse the movelog suite's
# constants via the same import path.


def run_console(engine, our_color, game_id, auto_opp, max_plies,
                clock_ms="w=900000,b=900000", timeout=300, engine_arg=()):
    """Run one tracer game in a temp --log-dir; return (rc, stdout, dir)."""
    tmp = tempfile.mkdtemp(prefix="e2e-")
    argv = [sys.executable, "-m", "console.main",
            "--engine", engine,
            "--our-color", our_color,
            "--clock-ms", clock_ms,
            "--log-dir", tmp,
            "--game-id", game_id,
            "--auto-opp", auto_opp,
            "--max-plies", str(max_plies)]
    for arg in engine_arg:
        argv += [f"--engine-arg={arg}"]
    p = subprocess.run(argv, capture_output=True, text=True, timeout=timeout,
                       cwd=REPO,
                       env={"PYTHONPATH": f"{REPO}/vendor:{REPO}/console/src",
                            "PATH": "/usr/bin:/bin"})
    return p.returncode, p.stdout + p.stderr, tmp


class RealEngineFullGameTests(unittest.TestCase):
    """Gate 1: the real binary plays a full game to a lint-clean log."""

    def test_full_game_real_engine_lint_clean_log(self):
        rc, out, tmp = run_console(
            "./src/stockfish", "w", "e2e01",
            auto_opp=("e7e5 g8f6 b8c6 f8c5 g8f6 f8e7 "
                      "e8g8 f8e8 a7a6 b7b5 c7c6 b5b4"),
            max_plies=12, timeout=300, clock_ms="w=60000,b=60000")
        self.assertEqual(rc, 0, out)
        self.assertIn("OK fullgame", out)

        log_path = pathlib.Path(tmp) / "game-e2e01.log"
        self.assertTrue(log_path.exists(), out)
        lines = log_path.read_text(encoding="utf-8").splitlines()
        move_rows = [ln for ln in lines if ln.startswith("src=")]
        self.assertGreaterEqual(len(move_rows), 12)
        # GAME_START + GAME_END in the journal.
        journal = pathlib.Path(tmp) / "journal-e2e01.jsonl"
        self.assertTrue(journal.exists())
        import json
        recs = [json.loads(ln) for ln in
                journal.read_text(encoding="utf-8").splitlines() if ln.strip()]
        events = [r.get("e") for r in recs]
        self.assertIn("GAME_START", events)
        self.assertIn("GAME_END", events)

        # Row-level acceptance: every row carries all eleven keys.
        row_keys = {"src", "move_no", "side", "uci", "depth", "nodes",
                    "score", "score_white", "engine_ms", "wall_ms", "pv"}
        for ln in move_rows:
            toks = dict(t.split("=", 1) for t in ln.split() if "=" in t)
            self.assertTrue(row_keys.issubset(toks.keys()), ln)
            # src=opp: §4.5 zeros + measured wall.
            if toks["src"] == "opp":
                self.assertEqual(toks["depth"], "0")
                self.assertEqual(toks["nodes"], "0")
                self.assertEqual(toks["score"], "-")
                self.assertEqual(toks["engine_ms"], "0")
                self.assertNotEqual(toks["wall_ms"], "0")
            # src=search: depth>0.
            if toks["src"] == "search":
                self.assertGreater(int(toks["depth"]), 0)
                self.assertGreater(int(toks["nodes"]), 0)

        # wall_ms ≥ engine_ms everywhere (T-02-13 invariant).
        for ln in move_rows:
            toks = dict(t.split("=", 1) for t in ln.split() if "=" in t)
            self.assertGreaterEqual(int(toks["wall_ms"]),
                                    int(toks["engine_ms"]), ln)

        # Lint zero failures.
        self.assertEqual(lint_log(log_path), [])

    def test_golden_fixture_passes_lint(self):
        """The committed golden log (from the real binary) lints clean."""
        golden = pathlib.Path(__file__).parent / "fixtures" / "golden-game.log"
        if not golden.exists():
            self.skipTest("golden fixture not yet generated")
        self.assertEqual(lint_log(golden), [])


class TracerHeaderTruthTests(unittest.TestCase):
    """CR-04 regression: the tracer's written header tells the truth.

    After a mock-engine tracer run the log's `# time-control` line equals
    the run's actual --clock-ms spec (format `M+S` from the ms values —
    the e2e runs 60000/60000 = `1+0`, NOT a hardcoded 15+10), and
    `# net-sha256` is a full 64-hex digest (not the 12-char prefix).
    """

    def test_mock_tracer_header_time_control_and_net_sha(self):
        rc, out, tmp = run_console(
            "tools/mock_engine.py", "w", "e2ehead",
            auto_opp="e7e5 g8f6", max_plies=2, timeout=60,
            clock_ms="w=60000,b=60000")
        self.assertEqual(rc, 0, out)
        self.assertIn("OK fullgame", out)
        log_path = pathlib.Path(tmp) / "game-e2ehead.log"
        self.assertTrue(log_path.exists(), out)
        lines = log_path.read_text(encoding="utf-8").splitlines()
        tc = [ln for ln in lines if ln.startswith("# time-control")]
        self.assertEqual(tc, ["# time-control 1+0"], lines)
        net = [ln for ln in lines if ln.startswith("# net-sha256")]
        self.assertEqual(len(net), 1, lines)
        digest = net[0].removeprefix("# net-sha256 ").split()[0]
        self.assertEqual(len(digest), 64, net[0])
        self.assertTrue(all(c in "0123456789abcdef" for c in digest),
                        net[0])
        # The 12-char prefix + prose form is gone.
        self.assertNotIn("1a298aa575a0 (", net[0])


class TerminalRowTests(unittest.TestCase):
    """Terminal bestmove (none) emits a lint-clean src=none row (§4.6)."""

    def test_terminal_none_row_lint_clean(self):
        rc, out, tmp = run_console(
            "tools/mock_engine.py", "w", "e2enone",
            auto_opp="e7e5", max_plies=99, timeout=60,
            engine_arg=("--none-bestmove",))
        self.assertEqual(rc, 0, out)
        log_path = pathlib.Path(tmp) / "game-e2enone.log"
        self.assertTrue(log_path.exists(), out)
        lines = log_path.read_text(encoding="utf-8").splitlines()
        none_rows = [ln for ln in lines if ln.startswith("src=none")]
        self.assertEqual(len(none_rows), 1, lines)
        toks = dict(t.split("=", 1) for t in none_rows[0].split() if "=" in t)
        self.assertEqual(toks["uci"], "(none)")
        self.assertEqual(toks["depth"], "0")
        self.assertEqual(toks["nodes"], "0")
        self.assertTrue(toks["score"], "score must be non-empty")
        self.assertNotEqual(toks["score"], "-")
        self.assertEqual(lint_log(log_path), [])


if __name__ == "__main__":
    unittest.main()
